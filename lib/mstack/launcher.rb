# frozen_string_literal: true

module Mstack
  # A stable path for the status line command. Plugins live in a versioned
  # cache directory that moves on every update, and the status line is a
  # user setting that mstack must not keep rewriting. So the setting points
  # at <home>/statusline, and that script is regenerated whenever the
  # plugin's location changes.
  class Launcher
    def initialize(home: Mstack.home, root: Mstack::ROOT)
      @path = File.join(home, "statusline")
      @root = root
    end

    attr_reader :path

    # Returns true when the script was (re)written.
    def install!
      return false if File.file?(@path) && File.read(@path) == script

      FileUtils.mkdir_p(File.dirname(@path))
      File.write(@path, script)
      File.chmod(0o755, @path)
      true
    end

    private

    def script
      <<~SH
        #!/bin/sh
        # Generated by mstack. Rewritten when the plugin moves (for example on update).
        exec "#{@root}/bin/mstack" statusline "$@"
      SH
    end
  end
end
